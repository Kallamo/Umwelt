// Builds the npm packages: @kallamo/umwelt and one package per platform that
// carries the umwelt executable, which the client finds on its own.
//
//   node scripts/pack-npm.mjs [--binary <platform>-<arch>=<path>]... [--output <dir>]
//
// Without --binary, the release executable of this machine is used
// (target/release). The main package declares every platform package as an
// optional dependency, so npm installs only the one that matches.
import { spawnSync } from 'node:child_process';
import { chmodSync, copyFileSync, cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { arch, platform } from 'node:os';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const PLATFORMS = {
  'win32-x64': { os: 'win32', cpu: 'x64', file: 'umwelt.exe' },
  'linux-x64': { os: 'linux', cpu: 'x64', file: 'umwelt' },
  'darwin-arm64': { os: 'darwin', cpu: 'arm64', file: 'umwelt' },
  'darwin-x64': { os: 'darwin', cpu: 'x64', file: 'umwelt' },
};

function options(name) {
  const values = [];
  for (let index = 0; index < process.argv.length; index++) {
    if (process.argv[index] === name) values.push(process.argv[index + 1]);
  }
  return values;
}

function run(command, args, cwd = root) {
  const result = spawnSync(command, args, { cwd, stdio: 'inherit', shell: process.platform === 'win32' });
  if (result.status !== 0) process.exit(result.status ?? 1);
}

const binaries = options('--binary').map(value => value.split('='));
if (binaries.length === 0) {
  run('cargo', ['build', '-p', 'umwelt-cli', '--release']);
  const local = `${platform()}-${arch()}`;
  if (!PLATFORMS[local]) throw new Error(`No package for platform ${local}.`);
  binaries.push([local, resolve(root, 'target/release', PLATFORMS[local].file)]);
}
const output = resolve(options('--output')[0] ?? resolve(root, 'target/npm'));
const staging = resolve(root, 'target/npm-staging');
rmSync(staging, { recursive: true, force: true });
mkdirSync(output, { recursive: true });

const main = JSON.parse(readFileSync(resolve(root, 'packages/umwelt/package.json'), 'utf8'));
const shared = {
  version: main.version,
  license: main.license,
  author: main.author,
  homepage: main.homepage,
  repository: main.repository,
  bugs: main.bugs,
  publishConfig: main.publishConfig,
};
// THIRD-PARTY-NOTICES.txt is generated by the release workflow (cargo-about);
// when present it goes into the platform packages, which carry the engine.
const notices = resolve(root, 'THIRD-PARTY-NOTICES.txt');
const legal = (directory, engine = false) => {
  copyFileSync(resolve(root, 'LICENSE'), resolve(directory, 'LICENSE'));
  copyFileSync(resolve(root, 'NOTICE'), resolve(directory, 'NOTICE'));
  copyFileSync(resolve(root, 'LICENSE-EXCEPTION.md'), resolve(directory, 'LICENSE-EXCEPTION.md'));
  if (engine && existsSync(notices)) copyFileSync(notices, resolve(directory, 'THIRD-PARTY-NOTICES.txt'));
};

// The client.
run('npm', ['run', 'build', '--workspace', main.name]);
const client = resolve(staging, 'umwelt');
mkdirSync(client, { recursive: true });
cpSync(resolve(root, 'packages/umwelt/dist'), resolve(client, 'dist'), { recursive: true });
copyFileSync(resolve(root, 'packages/umwelt/README.md'), resolve(client, 'README.md'));
legal(client);
const { scripts: _scripts, devDependencies: _dev, ...published } = main;
// npm adds LICENSE and README on its own, but not NOTICE or the exception.
published.files = [...main.files, 'NOTICE', 'LICENSE-EXCEPTION.md'];
published.optionalDependencies = Object.fromEntries(
  Object.keys(PLATFORMS).map(key => [`${main.name}-${key}`, main.version]),
);
writeFileSync(resolve(client, 'package.json'), JSON.stringify(published, null, 2) + '\n');
run('npm', ['pack', '--pack-destination', output], client);

// One package per platform with the executable.
for (const [key, path] of binaries) {
  const target = PLATFORMS[key];
  if (!target) throw new Error(`Unknown platform ${key}; use one of ${Object.keys(PLATFORMS).join(', ')}.`);
  if (!existsSync(path)) throw new Error(`Executable for ${key} not found: ${path}`);
  const directory = resolve(staging, `umwelt-${key}`);
  mkdirSync(resolve(directory, 'bin'), { recursive: true });
  const executable = resolve(directory, 'bin', target.file);
  copyFileSync(path, executable);
  if (target.os !== 'win32') chmodSync(executable, 0o755);
  legal(directory, true);
  writeFileSync(resolve(directory, 'README.md'), `# ${main.name}-${key}\n\nThe Umwelt engine for ${key}, used by [${main.name}](https://www.npmjs.com/package/${main.name}). Install \`${main.name}\` instead of this package.\n`);
  writeFileSync(resolve(directory, 'package.json'), JSON.stringify({
    name: `${main.name}-${key}`,
    ...shared,
    description: `The Umwelt engine for ${key}, used by ${main.name}.`,
    os: [target.os],
    cpu: [target.cpu],
    files: ['bin', 'NOTICE', 'LICENSE-EXCEPTION.md', 'THIRD-PARTY-NOTICES.txt'],
  }, null, 2) + '\n');
  run('npm', ['pack', '--pack-destination', output], directory);
}
console.log(`Packages written to ${output}`);
